/**
 * Returns the authentic student avatar image URL.
 * Prioritizes locally cached authentic student photos for blazing-fast 0ms local loading.
 * Never falls back to fake stock images.
 */
export function getGenuineStudentAvatar(
  userId?: string | null,
  email?: string | null,
  rawAvatarUrl?: string | null
): string | undefined {
  const base = (import.meta.env.BASE_URL || '/').replace(/\/?$/, '/');

  // 1. Direct ID match
  if (userId && STUDENT_AVATAR_FILES[userId]) {
    return `${base}avatars/${STUDENT_AVATAR_FILES[userId]}`;
  }

  // 2. Direct Email match
  if (email) {
    const cleanEmail = email.toLowerCase().trim();
    if (STUDENT_AVATAR_EMAILS[cleanEmail]) {
      return `${base}avatars/${STUDENT_AVATAR_EMAILS[cleanEmail]}`;
    }
  }

  // 3. Match from Supabase avatars bucket URL
  if (rawAvatarUrl && typeof rawAvatarUrl === 'string') {
    const trimmed = rawAvatarUrl.trim();
    if (trimmed.length > 0) {
      // Check if it's already a local avatar path
      if (trimmed.includes('/avatars/')) {
        const parts = trimmed.split('/avatars/');
        const fileName = parts[parts.length - 1];
        if (fileName && Object.values(STUDENT_AVATAR_FILES).includes(fileName)) {
          return `${base}avatars/${fileName}`;
        }
      }

      // Check if URL ends with a known student file
      for (const fileName of Object.values(STUDENT_AVATAR_FILES)) {
        if (trimmed.endsWith(fileName) || trimmed.includes(fileName)) {
          return `${base}avatars/${fileName}`;
        }
      }

      // If it's a real Base64 image uploaded by the student
      if (trimmed.startsWith('data:image/')) {
        return trimmed;
      }

      // If it's another valid http/https URL that is not a stock placeholder
      if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) {
        return trimmed;
      }
    }
  }

  return undefined;
}
